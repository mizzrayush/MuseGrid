import type { Track } from '../engine/store'

/**
 * Generates a valid Huygens-Fokker Scala (.scl) tuning file content.
 * Supported universally by VST synthesizers including Vital, Serum, Surge XT,
 * Pianoteq, Kontakt, DecentSampler, and Dexed.
 */
export function generateScalaContent(
  edo: number = 12,
  scaleName?: string,
  customCents?: number[]
): string {
  const lines: string[] = []
  const safeEdo = Math.max(1, Math.round(edo))
  const title = scaleName || (safeEdo === 12 ? '12-TET Standard Equal Temperament' : `${safeEdo}-EDO Equal Temperament`)

  lines.push(`! ${title.replace(/\s+/g, '_')}.scl`)
  lines.push(`! Generated by MuseGrid DAW`)
  lines.push(`! https://musegrid.app`)
  lines.push('!')
  lines.push(title)
  lines.push(safeEdo.toString())
  lines.push('!')

  if (customCents && customCents.length === safeEdo) {
    // Custom non-equal scale intervals
    for (let i = 0; i < safeEdo - 1; i++) {
      lines.push(customCents[i].toFixed(5))
    }
    lines.push('2/1')
  } else {
    // Standard equal division of the octave (EDO)
    const stepCents = 1200 / safeEdo
    for (let i = 1; i < safeEdo; i++) {
      lines.push((stepCents * i).toFixed(5))
    }
    lines.push('2/1')
  }

  return lines.join('\n') + '\n'
}

/**
 * Generates a matching Scala Keyboard Mapping (.kbm) file.
 * Tells VST synths to anchor Middle C (MIDI 60) to 261.63 Hz and map sequentially.
 */
export function generateKbmContent(
  edo: number = 12,
  rootMidi: number = 60,
  referenceFreq: number = 261.625565
): string {
  const lines: string[] = []
  const safeEdo = Math.max(1, Math.round(edo))

  lines.push('! MuseGrid_Tuning_Map.kbm')
  lines.push('! Size of map (0 for linear mapping):')
  lines.push('0')
  lines.push('! First MIDI note number to retune:')
  lines.push('0')
  lines.push('! Last MIDI note number to retune:')
  lines.push('127')
  lines.push('! Middle note where formal octave starts:')
  lines.push(rootMidi.toString())
  lines.push('! Reference note for which frequency is given:')
  lines.push(rootMidi.toString())
  lines.push('! Frequency of reference note (Hz):')
  lines.push(referenceFreq.toFixed(6))
  lines.push('! Scale degree formal octave:')
  lines.push(safeEdo.toString())

  return lines.join('\n') + '\n'
}

import { saveFileWithDialog } from './fileExport'

/**
 * Downloads a string or binary buffer with a Save File Dialog.
 */
export function downloadFile(content: string, filename: string, mimeType: string = 'text/plain') {
  const ext = filename.includes('.') ? filename.substring(filename.lastIndexOf('.') + 1) : 'scl'
  saveFileWithDialog(content, {
    defaultFilename: filename,
    title: `Export ${filename}`,
    extensions: [ext],
    mimeType
  })
}

/**
 * Generates and downloads a Scala (.scl) file for a given track or EDO division.
 */
export function exportTrackScala(track?: Track | null, filenamePrefix?: string): string {
  const edo = track?.edoDivision || 12
  const preset = track?.edoPreset
  let description = `${edo}-EDO Equal Temperament`
  if (preset === '53-edo' || edo === 53) description = '53-EDO Turkish Makam Holderian Comma Tuning'
  else if (preset === '24-edo' || edo === 24) description = '24-EDO Arabic Quarter-Tone System'
  else if (preset === '19-edo' || edo === 19) description = '19-EDO Renaissance Meantone Tuning'
  else if (preset === '31-edo' || edo === 31) description = '31-EDO Huygens-Fokker Meantone Tuning'
  else if (preset === '47-edo' || edo === 47) description = '47-EDO Extended Microtonal Temperament'

  const content = generateScalaContent(edo, description)
  const baseName = filenamePrefix || (track?.name ? track.name.replace(/\s+/g, '-').toLowerCase() : 'musegrid')
  const filename = `${baseName}_${edo}edo.scl`
  downloadFile(content, filename, 'text/plain')
  return filename
}

export interface ScalaScale {
  name: string
  count: number
  cents: number[]
  periodCents: number
  isEdo: boolean
  detectedEdo?: number
}

/**
 * Parses the content of a standard Huygens-Fokker Scala (.scl) tuning file.
 * Handles comments (!), human descriptions, note counts, cents, ratios,
 * and detects equal divisions of the octave (EDO).
 */
export function parseScalaContent(content: string): ScalaScale {
  const rawLines = content.split(/\r?\n/)
  const cleanLines: string[] = []

  for (const raw of rawLines) {
    const trimmed = raw.trim()
    if (!trimmed || trimmed.startsWith('!')) continue
    const noInline = trimmed.split('!')[0].trim()
    if (noInline) {
      cleanLines.push(noInline)
    }
  }

  if (cleanLines.length < 2) {
    throw new Error('Invalid Scala file: insufficient lines or missing header')
  }

  const name = cleanLines[0]
  const count = parseInt(cleanLines[1], 10)
  if (isNaN(count) || count <= 0) {
    throw new Error(`Invalid Scala file: invalid scale note count "${cleanLines[1]}"`)
  }

  const pitchLines = cleanLines.slice(2, 2 + count)
  const cents: number[] = []

  for (const line of pitchLines) {
    const token = line.trim().split(/\s+/)[0]
    if (token.includes('.')) {
      const val = parseFloat(token)
      if (!isNaN(val)) cents.push(val)
    } else if (token.includes('/')) {
      const [numStr, denStr] = token.split('/')
      const num = parseFloat(numStr)
      const den = parseFloat(denStr)
      if (!isNaN(num) && !isNaN(den) && den !== 0 && num > 0) {
        const ratioCents = 1200 * Math.log2(num / den)
        cents.push(ratioCents)
      }
    } else {
      const num = parseFloat(token)
      if (!isNaN(num) && num > 0) {
        const ratioCents = 1200 * Math.log2(num)
        cents.push(ratioCents)
      }
    }
  }

  const periodCents = cents.length > 0 ? cents[cents.length - 1] : 1200
  const isOctaveBased = Math.abs(periodCents - 1200) < 0.5

  let isEdo = false
  let detectedEdo: number | undefined = undefined

  if (isOctaveBased && cents.length === count) {
    const step = 1200 / count
    let maxDeviation = 0
    for (let i = 0; i < count; i++) {
      const expected = (i + 1) * step
      const dev = Math.abs(cents[i] - expected)
      if (dev > maxDeviation) maxDeviation = dev
    }
    // If intervals are within 1.0 cent of equal division, recognize as EDO
    if (maxDeviation <= 1.0) {
      isEdo = true
      detectedEdo = count
    }
  }

  return {
    name,
    count,
    cents,
    periodCents,
    isEdo,
    detectedEdo: detectedEdo || count
  }
}

